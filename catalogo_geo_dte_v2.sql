CREATE TABLE IF NOT EXISTS geo_departamento (
  codigo CHAR(2) PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  es_extranjero BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT geo_departamento_codigo_chk CHECK (codigo ~ '^[0-9]{2}$')
);

CREATE TABLE IF NOT EXISTS geo_municipio (
  departamento_codigo CHAR(2) NOT NULL REFERENCES geo_departamento (codigo),
  codigo CHAR(2) NOT NULL,
  nombre VARCHAR(80) NOT NULL,
  es_extranjero BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (departamento_codigo, codigo),
  CONSTRAINT geo_municipio_codigo_chk CHECK (codigo ~ '^[0-9]{2}$')
);

CREATE TABLE IF NOT EXISTS geo_distrito (
  id VARCHAR(8) PRIMARY KEY,
  departamento_codigo CHAR(2) NOT NULL,
  municipio_codigo CHAR(2) NOT NULL,
  codigo CHAR(2) NOT NULL,
  nombre VARCHAR(120) NOT NULL,
  nombre_catalogo_mh VARCHAR(120) NOT NULL,
  es_extranjero BOOLEAN NOT NULL DEFAULT FALSE,
  FOREIGN KEY (departamento_codigo) REFERENCES geo_departamento (codigo),
  FOREIGN KEY (departamento_codigo, municipio_codigo) REFERENCES geo_municipio (departamento_codigo, codigo),
  UNIQUE (departamento_codigo, codigo),
  CONSTRAINT geo_distrito_codigo_chk CHECK (codigo ~ '^[0-9]{2}$'),
  CONSTRAINT geo_distrito_id_chk CHECK (id ~ '^[0-9]{2}-[0-9]{2}-[0-9]{2}$')
);

CREATE INDEX IF NOT EXISTS geo_distrito_nombre_idx ON geo_distrito (nombre);
CREATE INDEX IF NOT EXISTS geo_municipio_nombre_idx ON geo_municipio (nombre);

